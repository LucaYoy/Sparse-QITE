#!/usr/bin/env python3
"""Create an HTCondor batch for selected completed QITE trajectories.

First generate and run the QITE configurations. Then edit the parameter block
in ``main()`` and run:

    python scripts/Generate_Transpilation_condor_batch.py

Each generated Condor process reads one completed QITE trajectory and calls
``Run_Transpilation_cluster.py``. Transpilation batches are kept separately
under ``condor/transpilation_batches``.
"""

from __future__ import annotations

import json
import shlex
import sys
from pathlib import Path
from typing import Any


SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_DIR = SCRIPT_DIR.parent
if str(PROJECT_DIR) not in sys.path:
    sys.path.insert(0, str(PROJECT_DIR))

from Generate_QITE_condor_batch import (
    parameter_fingerprint,
    safe_name,
    selected_configurations,
)
from Run_QITE_cluster import load_config, resolve_output_dir


def batch_name(
    qite_parameters: dict[str, Any],
    transpilation: dict[str, Any],
    label: str,
) -> str:
    """Build a readable name plus a hash of QITE and transpiler settings."""
    complete_selection = {
        "qite_parameters": qite_parameters,
        "transpilation": transpilation,
    }
    readable = safe_name(label)
    if not readable:
        raise ValueError("batch_label must contain at least one letter or number.")
    return f"{readable}_{parameter_fingerprint(complete_selection)}"


def require_completed_results(
    selected: list[tuple[Path, str]],
) -> None:
    """Reject configurations whose final trajectory or states are unavailable."""
    missing: list[Path] = []
    for config_path, _ in selected:
        config = load_config(config_path)
        result_dir = resolve_output_dir(config)
        for filename in ("trajectory.npz", "states.npz"):
            path = result_dir / filename
            if not path.is_file():
                missing.append(path)
    if missing:
        listing = "\n".join(f"  - {path}" for path in missing)
        raise FileNotFoundError(
            "Transpilation requires completed QITE results. Missing:\n" + listing
        )


def render_config_list(selected: list[tuple[Path, str]]) -> str:
    """Create the queue input containing a config path and readable job name."""
    return "".join(f"{path} {job_name}\n" for path, job_name in selected)


def render_run_script(transpilation: dict[str, Any]) -> str:
    """Create the worker wrapper with fixed transpilation options."""
    arguments = [
        "--optimization-level",
        str(transpilation["optimization_level"]),
        "--basis-gates",
        *[str(gate) for gate in transpilation["basis_gates"]],
    ]
    if transpilation["hamiltonian_gate"]:
        arguments.append("--hamiltonian-gate")
    if transpilation["compute_unitary_error"]:
        arguments.append("--compute-unitary-error")
    if transpilation["overwrite_outputs"]:
        arguments.append("--overwrite")
    rendered_arguments = " ".join(shlex.quote(argument) for argument in arguments)

    return f"""#!/usr/bin/env bash
set -euo pipefail

if [[ $# -ne 1 ]]; then
    echo "Usage: $0 CONFIG.toml" >&2
    exit 2
fi

SCRIPT_DIR="$(cd -- "$(dirname -- "${{BASH_SOURCE[0]}}")" && pwd)"
PROJECT_DIR="$(cd -- "$SCRIPT_DIR/../../.." && pwd)"
CONFIG_PATH="$1"
cd "$PROJECT_DIR"

if [[ ! -f "$CONFIG_PATH" ]]; then
    echo "Configuration file not found: $CONFIG_PATH" >&2
    exit 2
fi

PYTHON_EXECUTABLE="${{QITE_PYTHON:-python}}"
echo "Host: $(hostname)"
echo "Working directory: $PWD"
echo "Python: $PYTHON_EXECUTABLE"
echo "QITE configuration: $CONFIG_PATH"

exec "$PYTHON_EXECUTABLE" scripts/Run_Transpilation_cluster.py \
    "$CONFIG_PATH" {rendered_arguments}
"""


def render_submit_file(
    batch_dir: Path,
    cpus: int,
    memory: str,
    disk: str,
    job_flavour: str,
) -> str:
    """Create one Condor description queuing all selected configurations."""
    relative_batch = batch_dir.relative_to(PROJECT_DIR)
    return f"""# Generated by scripts/Generate_Transpilation_condor_batch.py.

universe = vanilla
initialdir = $ENV(PWD)
executable = {relative_batch}/run.sh
arguments = $(config)

should_transfer_files = NO
getenv = True

cpus = {cpus}
request_cpus = $(cpus)
request_memory = {memory}
request_disk = {disk}
environment = "OMP_NUM_THREADS=$(cpus) OPENBLAS_NUM_THREADS=$(cpus) MKL_NUM_THREADS=$(cpus) NUMEXPR_NUM_THREADS=$(cpus)"

+JobFlavour = "{job_flavour}"

log = {relative_batch}/condor_logs/log/batch_$(Cluster).log
output = {relative_batch}/condor_logs/out/$(job_name)_$(Cluster)_$(Process).out
error = {relative_batch}/condor_logs/err/$(job_name)_$(Cluster)_$(Process).err

queue config,job_name from {relative_batch}/transpilation_config_list.txt
"""


def render_submit_script(batch_dir: Path) -> str:
    """Create a submission wrapper that works from any current directory."""
    relative_batch = batch_dir.relative_to(PROJECT_DIR)
    return f"""#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${{BASH_SOURCE[0]}}")" && pwd)"
PROJECT_DIR="$(cd -- "$SCRIPT_DIR/../../.." && pwd)"
cd "$PROJECT_DIR"

mkdir -p \
    {relative_batch}/condor_logs/log \
    {relative_batch}/condor_logs/out \
    {relative_batch}/condor_logs/err

echo "Submitting $(wc -l < {relative_batch}/transpilation_config_list.txt) transpilation job(s)."
condor_submit {relative_batch}/transpilation.sub
"""


def write_batch(
    batch_dir: Path,
    name: str,
    qite_parameters: dict[str, Any],
    transpilation: dict[str, Any],
    selected: list[tuple[Path, str]],
    resources: dict[str, Any],
    overwrite: bool,
) -> None:
    """Write a self-contained transpilation batch atomically."""
    batch_dir.mkdir(parents=True, exist_ok=True)
    manifest = {
        "batch_name": name,
        "qite_parameters": qite_parameters,
        "transpilation": transpilation,
        "resources": resources,
        "jobs": [
            {"job_id": job_name, "config": str(config_path)}
            for config_path, job_name in selected
        ],
    }
    files = {
        batch_dir / "selection.json": json.dumps(
            manifest, indent=2, sort_keys=True
        )
        + "\n",
        batch_dir / "transpilation_config_list.txt": render_config_list(selected),
        batch_dir / "run.sh": render_run_script(transpilation),
        batch_dir / "transpilation.sub": render_submit_file(
            batch_dir,
            resources["cpus"],
            resources["memory"],
            resources["disk"],
            resources["job_flavour"],
        ),
        batch_dir / "submit_all.sh": render_submit_script(batch_dir),
    }

    existing = [path for path in files if path.exists()]
    if existing and not overwrite:
        listing = "\n".join(f"  - {path}" for path in existing)
        raise FileExistsError(
            f"Batch files already exist:\n{listing}\n"
            "Set overwrite = True to replace them."
        )

    for path, contents in files.items():
        temporary = path.with_suffix(path.suffix + ".tmp")
        temporary.write_text(contents, encoding="utf-8")
        temporary.replace(path)

    (batch_dir / "run.sh").chmod(0o755)
    (batch_dir / "submit_all.sh").chmod(0o755)
    for stream in ("log", "out", "err"):
        (batch_dir / "condor_logs" / stream).mkdir(parents=True, exist_ok=True)


def main() -> None:
    # ------------------------------------------------------------------
    # EDIT THIS BLOCK TO SELECT COMPLETED QITE RUNS TO TRANSPILE.
    # Values must match existing TOML configurations.
    # ------------------------------------------------------------------
    qite_parameters = {
        "n_qubits": [8],
        "D": [4],
        "N": [100],
        "dt": [0.05],
        "method": ["default"],
        # "method": ["default", "vanilla_lasso"],
        "model": ["tfim"],
        "J": [0.5],
        "h": [1.0],
        "T": [2],
        "cluster_lambda": [0.5],
        "lasso_lambda": [1e-3],
        "lasso_max_iter": 500,
        "lasso_tol": 1e-8,
        "jaccard_cumulative_min": [0.99],
        "jaccard_patience": [3],
        "support_tol": [1e-14],
        "checkpoint_enabled": True,
        "checkpoint_every_steps": 1,
        "initial_basis_state": 0,
        "verbose": False,
    }

    transpilation = {
        "optimization_level": 1,
        "basis_gates": ["u3", "cx"],
        "hamiltonian_gate": False,
        # Full-unitary validation scales as O(4**n); normally leave disabled.
        "compute_unitary_error": False,
        "overwrite_outputs": True,
    }

    resources = {
        "cpus": 1,
        "memory": "8GB",
        "disk": "4GB",
        "job_flavour": "tomorrow",
    }
    batch_label = "tfim_n8_D4_default_qite_transpilation"
    overwrite_batch = True
    # ------------------------------------------------------------------

    selected = selected_configurations(
        qite_parameters, PROJECT_DIR / "configs" / "generated"
    )
    require_completed_results(selected)
    name = batch_name(qite_parameters, transpilation, batch_label)
    batch_dir = PROJECT_DIR / "condor" / "transpilation_batches" / name
    write_batch(
        batch_dir,
        name,
        qite_parameters,
        transpilation,
        selected,
        resources,
        overwrite_batch,
    )
    print(f"Created transpilation batch with {len(selected)} job(s): {batch_dir}")
    print(f"Submit it with: {batch_dir / 'submit_all.sh'}")


if __name__ == "__main__":
    main()
