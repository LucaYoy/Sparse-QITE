#!/usr/bin/env python3
"""Generate TOML configuration files for QITE parameter scans.

Edit the clearly marked parameter block inside ``main()``, then run::

    python scripts/Generate_QITE_configs.py

Every relevant list is combined as a Cartesian product. Standard QITE gets one
file per physical setup, vanilla sparse-QITE gets one per LASSO lambda, and
Jaccard-LASSO additionally scans its cumulative-support parameters.
"""

from __future__ import annotations

import itertools
import os
from pathlib import Path
from typing import Any, Iterable


SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_DIR = SCRIPT_DIR.parent

def number_tag(value: float | int) -> str:
    """Return a compact number that is safe and readable in a file name."""
    text = f"{value:g}"
    return text.replace("-", "m").replace("+", "p").replace(".", "p")


def quoted(value: str | Path) -> str:
    """Quote a string using TOML-compatible double quotes."""
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def method_file_tag(
    method: str,
    lasso_lambda: float | None,
    jaccard_cumulative_min: float | None = None,
    jaccard_patience: int | None = None,
    support_tol: float | None = None,
) -> str:
    """Return a unique, readable output name for one evolution method."""
    if method == "vanilla_lasso":
        return f"sparse_qite_lambda_{number_tag(lasso_lambda)}"
    if method == "Jaccard_lasso":
        if None in (jaccard_cumulative_min, jaccard_patience, support_tol):
            raise ValueError("Jaccard_lasso requires all Jaccard parameters.")
        return (
            f"jaccard_lasso_lambda_{number_tag(lasso_lambda)}_"
            f"Jcum{number_tag(jaccard_cumulative_min)}_"
            f"P{jaccard_patience}_stol{number_tag(support_tol)}"
        )
    if method == "default":
        return "qite_default"
    return f"qite_{method}"


def physical_folder_name(job: dict[str, Any]) -> str:
    """Name the folder using the parameters shared by its method/lambda files."""
    name = (
        f"{job['model']}_n{job['n_qubits']}_D{job['D']}_"
        f"N{job['N']}_dt{number_tag(job['dt'])}_T{job['T']}"
    )
    if job["model"] == "tfim":
        name += f"_J{number_tag(job['J'])}_h{number_tag(job['h'])}"
    elif job["model"].startswith("heisenberg"):
        name += f"_J{number_tag(job['J'])}"
    elif job["model"] == "cluster_ising":
        name += f"_lambda{number_tag(job['cluster_lambda'])}"
    return name


def relative_path(target: Path, start: Path) -> Path:
    """Make generated configurations portable with paths relative to themselves."""
    return Path(os.path.relpath(target.resolve(), start=start.resolve()))


def render_toml(job: dict[str, Any], result_dir: Path, config_dir: Path) -> str:
    output_dir = relative_path(result_dir, config_dir)
    lines = [
        "# Generated by scripts/Generate_QITE_configs.py.",
        "# This file is self-contained and can be submitted as one Condor job.",
        "",
        "[simulation]",
        f"n_qubits = {job['n_qubits']}",
        f"D = {job['D']}",
        f"N = {job['N']}",
        f"dt = {job['dt']!r}",
        f"initial_basis_state = {job['initial_basis_state']}",
        f"verbose = {str(job['verbose']).lower()}",
        f"method = {quoted(job['method'])}",
        "",
        "[hamiltonian]",
        f"model = {quoted(job['model'])}",
        f"J = {job['J']!r}",
        f"h = {job['h']!r}",
        f"T = {job['T']}",
        f"cluster_lambda = {job['cluster_lambda']!r}",
        "",
        "[lasso]",
        f"lasso_lambda = {job['lasso_lambda']!r}",
        f"lasso_max_iter = {job['lasso_max_iter']}",
        f"lasso_tol = {job['lasso_tol']!r}",
        "",
        "[jaccard]",
        f"jaccard_cumulative_min = {job['jaccard_cumulative_min']!r}",
        f"jaccard_patience = {job['jaccard_patience']}",
        f"support_tol = {job['support_tol']!r}",
        "",
        "[output]",
        f"output_dir = {quoted(output_dir)}",
        "",
    ]
    return "\n".join(lines)


def parameter_jobs(parameters: dict[str, Any]) -> Iterable[dict[str, Any]]:
    """Yield valid jobs in deterministic Cartesian-product order."""
    common_product = itertools.product(
        parameters["n_qubits"],
        parameters["D"],
        parameters["N"],
        parameters["dt"],
        parameters["T"],
        parameters["method"],
    )
    common_values = list(common_product)

    for model in parameters["model"]:
        if model == "tfim":
            model_values = itertools.product(
                parameters["J"], parameters["h"], [parameters["cluster_lambda"][0]]
            )
        elif model == "cluster_ising":
            model_values = itertools.product(
                [parameters["J"][0]], [parameters["h"][0]], parameters["cluster_lambda"]
            )
        else:
            model_values = itertools.product(
                parameters["J"], [parameters["h"][0]], [parameters["cluster_lambda"][0]]
            )

        for (n, D, N, dt, T, method), (J, h, cluster_lambda) in itertools.product(
            common_values, model_values
        ):
            if D > n:
                print(f"Skipping invalid combination n_qubits={n}, D={D}.")
                continue
            if model == "cluster_ising" and T < 3:
                print(f"Skipping Cluster-Ising combination with T={T}; it requires T >= 3.")
                continue

            jaccard_min_values = parameters.get("jaccard_cumulative_min", [0.99])
            jaccard_patience_values = parameters.get("jaccard_patience", [3])
            support_tolerances = parameters.get("support_tol", [1e-14])

            if method == "Jaccard_lasso":
                method_values = itertools.product(
                    parameters["lasso_lambda"],
                    jaccard_min_values,
                    jaccard_patience_values,
                    support_tolerances,
                )
            elif method == "vanilla_lasso":
                method_values = itertools.product(
                    parameters["lasso_lambda"],
                    [jaccard_min_values[0]],
                    [jaccard_patience_values[0]],
                    [support_tolerances[0]],
                )
            else:
                method_values = [(
                    parameters["lasso_lambda"][0],
                    jaccard_min_values[0],
                    jaccard_patience_values[0],
                    support_tolerances[0],
                )]

            for (
                lasso_lambda,
                jaccard_cumulative_min,
                jaccard_patience,
                support_tol,
            ) in method_values:
                yield {
                    "model": model,
                    "n_qubits": n,
                    "D": D,
                    "N": N,
                    "dt": dt,
                    "T": T,
                    "J": J,
                    "h": h,
                    "cluster_lambda": cluster_lambda,
                    "method": method,
                    "lasso_lambda": lasso_lambda,
                    "lasso_max_iter": parameters["lasso_max_iter"],
                    "lasso_tol": parameters["lasso_tol"],
                    "jaccard_cumulative_min": jaccard_cumulative_min,
                    "jaccard_patience": jaccard_patience,
                    "support_tol": support_tol,
                    "initial_basis_state": parameters["initial_basis_state"],
                    "verbose": parameters["verbose"],
                }


def write_config(path: Path, contents: str, overwrite: bool) -> bool:
    """Write one configuration atomically; return False when it was skipped."""
    if path.exists() and not overwrite:
        print(f"Skipping existing file: {path}")
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = path.with_suffix(path.suffix + ".tmp")
    temporary_path.write_text(contents, encoding="utf-8")
    temporary_path.replace(path)
    return True


def main() -> None:
    # -----------------------------------------------------------------------
    # EDIT THE PARAMETER LISTS IN THIS BLOCK.
    # Every combination of these values will become a TOML job configuration.
    # -----------------------------------------------------------------------
    parameters = {
        "n_qubits": [8],
        "D": [6],
        "N": [100],
        "dt": [0.05],
        #"method": ["default", "vanilla_lasso"],
        # Add "Jaccard_lasso" to generate cumulative-Jaccard configurations.
        "method": ["Jaccard_lasso"],
        "model": ["tfim"],
        #"model" : ["heisenberg_pbc"],

        # Hamiltonian parameters
        "J": [1.0],
        "h": [0.5],
        "T": [2],
        "cluster_lambda": [0.5],

        # Sparse-QITE parameters
        #"lasso_lambda": [1e-2,1e-3,1e-4],
        "lasso_lambda": [1e-3],
        #"lasso_lambda" : [1e-5,3e-5,1e-4,3e-4,1e-3,3e-3,1e-2,3e-2,1e-1,3e-1,1.0,],
        #"lasso_lambda" : [0.02, 0.05, 0.15, 0.20, 0.25],
        "lasso_max_iter": 500,
        "lasso_tol": 1e-8,

        # Cumulative-Jaccard support-freezing parameters. These lists are
        # combined only when method="Jaccard_lasso".
        "jaccard_cumulative_min": [0.99],
        "jaccard_patience": [3],
        "support_tol": [1e-14],

        # Initial state |initial_basis_state>
        "initial_basis_state": 0,
        #"initial_basis_state": 85,
        "verbose": False,
    }

    config_root = PROJECT_DIR / "configs" / "generated"
    results_root = PROJECT_DIR / "outputs" / "qite_runs"
    overwrite = False
    # -----------------------------------------------------------------------

    config_root = config_root.expanduser().resolve()
    results_root = results_root.expanduser().resolve()

    created = 0
    skipped = 0
    for job in parameter_jobs(parameters):
        folder_name = physical_folder_name(job)
        config_dir = config_root / folder_name
        file_tag = method_file_tag(
            job["method"],
            job["lasso_lambda"],
            job["jaccard_cumulative_min"],
            job["jaccard_patience"],
            job["support_tol"],
        )
        config_path = config_dir / f"{file_tag}.toml"
        result_dir = results_root / folder_name / file_tag
        contents = render_toml(job, result_dir, config_dir)
        if write_config(config_path, contents, overwrite):
            created += 1
        else:
            skipped += 1

    print(f"Created {created} configuration file(s) under {config_root}")
    if skipped:
        print(f"Skipped {skipped} existing file(s); use --overwrite to replace them.")


if __name__ == "__main__":
    main()
