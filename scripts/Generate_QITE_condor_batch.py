#!/usr/bin/env python3
"""Create an HTCondor batch for a selected subset of QITE configurations.

First generate the TOML catalog with ``Generate_QITE_configs.py``. Then edit
the parameter block in ``main()`` below and run::

    python scripts/Generate_QITE_condor_batch.py

The generated batch queues only the selected TOML files, not the entire
``configs/generated`` tree.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
from typing import Any

from Generate_QITE_configs import (
    method_file_tag,
    parameter_jobs,
    physical_folder_name,
)


SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_DIR = SCRIPT_DIR.parent


def safe_name(text: str) -> str:
    """Convert a human label into a safe directory-name component."""
    return re.sub(r"[^A-Za-z0-9_-]+", "_", text.strip()).strip("_")


def parameter_fingerprint(parameters: dict[str, Any]) -> str:
    """Return a short deterministic identifier for the complete selection."""
    canonical = json.dumps(parameters, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:8]


def make_batch_name(parameters: dict[str, Any], label: str, suffix: str = "") -> str:
    """Combine a readable experiment label with a parameter-grid fingerprint."""
    safe_label = safe_name(label)
    if not safe_label:
        raise ValueError("batch_label must contain at least one letter or number.")
    parts = [safe_label, parameter_fingerprint(parameters)]
    safe_suffix = safe_name(suffix)
    if safe_suffix:
        parts.append(safe_suffix)
    return "_".join(parts)


def selected_configurations(
    parameters: dict[str, Any],
    config_root: Path,
) -> list[tuple[Path, str]]:
    """Return existing selected configs and unique, Condor-safe job names."""
    selected: list[tuple[Path, str]] = []
    missing: list[Path] = []

    for job in parameter_jobs(parameters):
        folder = physical_folder_name(job)
        file_tag = method_file_tag(
            job["method"],
            job["lasso_lambda"],
            job["jaccard_cumulative_min"],
            job["jaccard_patience"],
            job["support_tol"],
        )
        config_path = config_root / folder / f"{file_tag}.toml"
        if not config_path.is_file():
            missing.append(config_path)
            continue
        selected.append((config_path.resolve(), ""))

    if missing:
        formatted = "\n".join(f"  - {path}" for path in missing)
        raise FileNotFoundError(
            "The following selected configurations do not exist:\n"
            f"{formatted}\nRun scripts/Generate_QITE_configs.py first."
        )
    if not selected:
        raise ValueError("The selection produced no Condor jobs.")

    # Guard against accidentally selecting the same file more than once.
    paths = [path for path, _ in selected]
    if len(paths) != len(set(paths)):
        raise ValueError("The parameter selection contains duplicate configuration files.")
    width = max(4, len(str(len(selected) - 1)))
    return [(path, f"job_{index:0{width}d}") for index, (path, _) in enumerate(selected)]


def render_config_list(selected: list[tuple[Path, str]]) -> str:
    """Create the two-column queue input: config path and readable job name."""
    return "".join(f"{path} {job_name}\n" for path, job_name in selected)


def render_selection_manifest(
    batch_name: str,
    parameters: dict[str, Any],
    selected: list[tuple[Path, str]],
    cpus: int,
    memory: str,
    disk: str,
    job_flavour: str,
) -> str:
    """Record everything needed to identify and reproduce a generated batch."""
    manifest = {
        "batch_name": batch_name,
        "parameter_fingerprint": parameter_fingerprint(parameters),
        "parameters": parameters,
        "resources": {
            "cpus": cpus,
            "memory": memory,
            "disk": disk,
            "job_flavour": job_flavour,
        },
        "jobs": [
            {"job_id": job_name, "config": str(config_path)}
            for config_path, job_name in selected
        ],
    }
    return json.dumps(manifest, indent=2, sort_keys=True) + "\n"


def render_submit_file(
    batch_dir: Path,
    cpus: int,
    memory: str,
    disk: str,
    job_flavour: str,
) -> str:
    """Create one submit description that queues the selected config list."""
    relative_batch = batch_dir.relative_to(PROJECT_DIR)
    queue_file = relative_batch / "qite_config_list.txt"
    log_root = relative_batch / "condor_logs"
    return f"""# Generated by scripts/Generate_QITE_condor_batch.py.
# Submit with: {relative_batch}/submit_all.sh

universe = vanilla
initialdir = $ENV(PWD)
executable = {relative_batch}/run.sh
arguments = $(config)

should_transfer_files = NO
getenv = True

cpus = {cpus}
request_cpus = $(cpus)
request_memory = {memory}
request_disk = {disk}
environment = \"OMP_NUM_THREADS=$(cpus) OPENBLAS_NUM_THREADS=$(cpus) MKL_NUM_THREADS=$(cpus) NUMEXPR_NUM_THREADS=$(cpus)\"

+JobFlavour = \"{job_flavour}\"

log = {log_root}/log/batch_$(Cluster).log
output = {log_root}/out/$(job_name)_$(Cluster)_$(Process).out
error = {log_root}/err/$(job_name)_$(Cluster)_$(Process).err

queue config,job_name from {queue_file}
"""


def render_run_script() -> str:
    """Create the worker wrapper stored inside each self-contained batch."""
    return """#!/usr/bin/env bash
set -euo pipefail

if [[ $# -ne 1 ]]; then
    echo "Usage: $0 CONFIG.toml" >&2
    exit 2
fi

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd -- "$SCRIPT_DIR/../../.." && pwd)"
CONFIG_PATH="$1"
cd "$PROJECT_DIR"

if [[ ! -f "$CONFIG_PATH" ]]; then
    echo "Configuration file not found: $CONFIG_PATH" >&2
    exit 2
fi

PYTHON_EXECUTABLE="${QITE_PYTHON:-python}"
echo "Host: $(hostname)"
echo "Working directory: $PWD"
echo "Python: $PYTHON_EXECUTABLE"
echo "Configuration: $CONFIG_PATH"

exec "$PYTHON_EXECUTABLE" scripts/Run_QITE_cluster.py "$CONFIG_PATH"
"""


def render_submit_script(batch_dir: Path) -> str:
    """Create a submission wrapper that works from any current directory."""
    relative_batch = batch_dir.relative_to(PROJECT_DIR)
    return f"""#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=\"$(cd -- \"$(dirname -- \"${{BASH_SOURCE[0]}}\")\" && pwd)\"
PROJECT_DIR=\"$(cd -- \"$SCRIPT_DIR/../../..\" && pwd)\"
cd \"$PROJECT_DIR\"

mkdir -p \\
    {relative_batch}/condor_logs/log \\
    {relative_batch}/condor_logs/out \\
    {relative_batch}/condor_logs/err

echo \"Submitting $(wc -l < {relative_batch}/qite_config_list.txt) selected QITE job(s).\"
condor_submit {relative_batch}/qite.sub
"""


def write_batch(
    batch_dir: Path,
    batch_name: str,
    parameters: dict[str, Any],
    selected: list[tuple[Path, str]],
    cpus: int,
    memory: str,
    disk: str,
    job_flavour: str,
    overwrite: bool,
) -> None:
    """Write all batch files and create the required log directories."""
    batch_dir.mkdir(parents=True, exist_ok=True)
    files = {
        batch_dir / "selection.json": render_selection_manifest(
            batch_name, parameters, selected, cpus, memory, disk, job_flavour
        ),
        batch_dir / "qite_config_list.txt": render_config_list(selected),
        batch_dir / "qite.sub": render_submit_file(
            batch_dir, cpus, memory, disk, job_flavour
        ),
        batch_dir / "run.sh": render_run_script(),
        batch_dir / "submit_all.sh": render_submit_script(batch_dir),
    }

    existing = [path for path in files if path.exists()]
    if existing and not overwrite:
        formatted = "\n".join(f"  - {path}" for path in existing)
        raise FileExistsError(
            f"Batch files already exist:\n{formatted}\nSet overwrite = True to replace them."
        )

    for path, contents in files.items():
        temporary = path.with_suffix(path.suffix + ".tmp")
        temporary.write_text(contents, encoding="utf-8")
        temporary.replace(path)

    (batch_dir / "run.sh").chmod(0o755)
    (batch_dir / "submit_all.sh").chmod(0o755)
    for stream in ("log", "out", "err"):
        (batch_dir / "condor_logs" / stream).mkdir(parents=True, exist_ok=True)


